const { chromium } = require('playwright');
const [file, out] = process.argv.slice(2);
(async () => {
  const b = await chromium.launch(); const errs = [];
  const pg = await b.newPage({ viewport: { width: 1200, height: 800 } });
  pg.on('pageerror', e => errs.push(e.message));
  await pg.addInitScript(() => { try { localStorage.setItem('gezi-onboarded', '1'); } catch (_) {} });
  await pg.goto('file://' + file + '?gezi=ayasofya,topkapi,xx,galatakulesi'); await pg.waitForTimeout(2200);
  const shared = await pg.evaluate(() => ({ kind: XV && XV.kind, arg: XV && XV.arg, txt: document.getElementById('xbody').innerText.slice(0, 120).replace(/\n/g, ' | ') }));
  await pg.evaluate(() => { const bt = [...document.querySelectorAll('button')].find(x => x.dataset.a === 'demo'); bt && bt.click(); }); await pg.waitForTimeout(900);
  await pg.evaluate(() => select('pamukkale')); await pg.waitForTimeout(400);
  const det = await pg.evaluate(() => ({ season: !!document.querySelector('#detail .season'), dishes: document.querySelector('#detail .dishes')?.innerText.replace(/\n/g, ' | ') }));
  await pg.screenshot({ path: out + '/detail.png' });
  await pg.evaluate(() => { ['ayasofya', 'pamukkale', 'goreme', 'sumela', 'nemrut', 'efes'].forEach(id => byId(id) && S.visited.add(id)); A.mpaint(); });
  await pg.waitForTimeout(500);
  const paint = await pg.evaluate(() => ({ paths: document.querySelectorAll('.pmap path').length, on: document.querySelectorAll('.pmap path.on').length, txt: document.querySelector('.pbig')?.innerText }));
  await pg.screenshot({ path: out + '/paint.png', clip: { x: 0, y: 0, width: 600, height: 800 } });
  const png = await pg.evaluate(async () => { const bl = await paintPNG(); const u = await new Promise(r => { const f = new FileReader(); f.onload = () => r(f.result); f.readAsDataURL(bl); }); return u; });
  require('fs').writeFileSync(out + '/share.png', Buffer.from(png.split(',')[1], 'base64'));
  await pg.evaluate(() => { hideX(); showView(); A.season(); });
  const seasonN = await pg.evaluate(() => results().length);
  await pg.evaluate(() => { A.season(); });
  const allN = await pg.evaluate(() => results().length);
  await pg.evaluate(() => { TRIP.splice(0, TRIP.length, 'ayasofya', 'topkapi'); showX('trip'); });
  const tsh = await pg.evaluate(() => !!document.querySelector('[data-a="tshare"]'));
  await pg.evaluate(() => { NOTE.list = [{ id: 'n1', kind: 'reply', who: 'Ayşe', place_id: 'ayasofya', read: false, created_at: new Date().toISOString() }, { id: 'n2', kind: 'approved', who: '?', place_id: 'pamukkale', read: true, created_at: new Date().toISOString() }]; showX('inbox'); renderX(); NOTE.unread = 3; noteBadge(); });
  await pg.waitForTimeout(300);
  const inbox = await pg.evaluate(() => ({ txt: document.getElementById('xbody').innerText.slice(0, 200).replace(/\n/g, ' | '), badge: document.querySelector('#acct .nbadge')?.textContent }));
  await pg.screenshot({ path: out + '/inbox.png', clip: { x: 0, y: 0, width: 600, height: 500 } });
  await pg.evaluate(() => { showX('city', 'Gaziantep', 'rec'); });
  const city = await pg.evaluate(() => document.querySelector('#xbody .dishes')?.innerText.replace(/\n/g, ' | '));
  console.log(JSON.stringify({ shared, det, paint, seasonN, allN, tsh, inbox, city }, null, 1), '\nhatalar:', errs.length ? errs : 'yok');
  await b.close();
})();
